"""CIEDE2000 check: both player colours against every ring of every look option.

    python3 art/tools/deltae_check.py            # prints markdown, writes art/direction/deltae.md

Per ring it reports ΔE00 against the dominant hue (the mid tile shade) and the worst case over
all of that ring's colours (four tile shades + two wall shades, or the four sky/space shades).
Verdict: under 10 = worm gets lost (FAIL), 10 to 20 = flag (relies on outline/eye), 20+ = OK.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from worm_looks import LOOKS, P1, P2, RINGS, de2000, dominant  # noqa: E402

FAIL, FLAG = 10.0, 20.0


def ring_colours(look, ring):
    return look["rings"][ring] if ring in look["rings"] else look[ring]


def verdict(v):
    return "FAIL" if v < FAIL else ("flag" if v < FLAG else "ok")


def table():
    out = ["| Option | Ring | dominant | P1 vs dom | P1 worst | P2 vs dom | P2 worst | verdict |",
           "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    worst = {}
    for k, look in LOOKS.items():
        for ring in RINGS:
            cols = ring_colours(look, ring)
            dom = dominant(look, ring)
            p1d, p2d = de2000(P1, dom), de2000(P2, dom)
            p1w = min(de2000(P1, c) for c in cols)
            p2w = min(de2000(P2, c) for c in cols)
            w = min(p1w, p2w)
            worst[k] = min(worst.get(k, 999), w)
            out.append(f"| {k.upper()} | {ring} | `{dom}` | {p1d:.1f} | {p1w:.1f} | {p2d:.1f} | {p2w:.1f} | {verdict(w)} |")
    out.append("")
    out.append("Worst case per option: " + ", ".join(f"{k.upper()} {v:.1f}" for k, v in worst.items()))
    return "\n".join(out), worst


def _main_lantern():
    md, worst = lantern_table()
    print(md)
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "..", "direction", "deltae_lantern.md"), "w") as f:
        f.write("# ΔE2000: both worms vs every Lantern Deep ring (Docket D92)\n\nGenerated by "
                "`python3 art/tools/deltae_check.py --lantern` from the shipped tile ramps "
                "(`art/tools/lantern_tiles.py`). P1 `%s`, P2 `%s`. Every tile, wall and accent "
                "colour of the ring counts. Under 10 FAIL, 10 to 20 flag, 20+ ok.\n\n" % (P1, P2) + md + "\n")
    sys.exit(1 if worst < FLAG else 0)


if __name__ == "__main__" and "--lantern" not in sys.argv:
    md, worst = table()
    print(md)
    here = os.path.dirname(os.path.abspath(__file__))
    dst = os.path.join(here, "..", "direction", "deltae.md")
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, "w") as f:
        f.write("# ΔE2000: player colours vs every ring\n\nGenerated by `art/tools/deltae_check.py`. "
                "P1 `%s`, P2 `%s`. Under 10 FAIL, 10 to 20 flag, 20+ ok.\n\n" % (P1, P2) + md + "\n")
    sys.exit(1 if min(worst.values()) < FAIL else 0)


# ---- the picked look (Docket D92): Lantern Deep's final game palette -------------------------
def lantern_rings():
    """Every colour a worm can be seen against, per ring, in the shipped Lantern tiles."""
    from lantern_tiles import RAMPS
    b = LOOKS["b"]
    return {
        "sky": b["sky"],
        "surface (grass crust)": RAMPS["grass"] + RAMPS["flower"],
        "topsoil": RAMPS["topsoil"] + RAMPS["mushroom"] + RAMPS["stem"] + RAMPS["root"],
        "dirt": RAMPS["dirt"] + RAMPS["clay"] + RAMPS["pebble"] + RAMPS["root"] + RAMPS["castings"],
        "rock": RAMPS["rock"] + RAMPS["ore"] + RAMPS["pebble"],
        "core": RAMPS["core"] + RAMPS["crystal"] + RAMPS["strange"],
        "space": b["space"],
    }


def lantern_table():
    out = ["| Ring | colours | P1 worst | against | P2 worst | against | verdict |",
           "| --- | --- | --- | --- | --- | --- | --- |"]
    worst = 999.0
    for ring, cols in lantern_rings().items():
        p1 = min((de2000(P1, c), c) for c in cols)
        p2 = min((de2000(P2, c), c) for c in cols)
        w = min(p1[0], p2[0])
        worst = min(worst, w)
        out.append(f"| {ring} | {len(cols)} | {p1[0]:.1f} | `{p1[1]}` | {p2[0]:.1f} | `{p2[1]}` | {verdict(w)} |")
    out.append("")
    out.append(f"Worst case: {worst:.1f}")
    return "\n".join(out), worst


if __name__ == "__main__" and "--lantern" in sys.argv:
    _main_lantern()
